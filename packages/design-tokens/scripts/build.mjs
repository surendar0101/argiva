// Compiles tokens to dist/: per-theme CSS scoped by [data-theme], one combined CSS file,
// a JS/TS theme registry for the app (admin theme picker) and a preview page.
import { readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import StyleDictionary from 'style-dictionary';
import { ROOT, flatten, loadThemes } from './lib.mjs';

process.chdir(ROOT);
const DIST = path.join(ROOT, 'dist');
const CSS = path.join(DIST, 'css');
rmSync(DIST, { recursive: true, force: true });

const themes = loadThemes();
const manifests = themes.map((t) => t.manifest);
const defaultTheme = manifests.find((m) => m.default);
const isThemeToken = (t) => t.filePath.replaceAll('\\', '/').includes('tokens/themes/') && t.path[0] !== 'palette';

for (const { manifest } of themes) {
  const { id } = manifest;
  const files = [
    {
      destination: `themes/${id}.css`,
      format: 'css/variables',
      filter: isThemeToken,
      options: { selector: manifest.default ? `:root, [data-theme="${id}"]` : `[data-theme="${id}"]`, outputReferences: false },
    },
  ];
  if (manifest.default) {
    files.push(
      {
        destination: 'base.css',
        format: 'css/variables',
        filter: (t) => t.filePath.replaceAll('\\', '/').includes('tokens/base/'),
        options: { selector: ':root' },
      },
      {
        destination: 'components.css',
        format: 'css/variables',
        filter: (t) => t.path[0] === 'component',
        // Re-declared on every [data-theme] element so nested themes (previews) resolve to their own values.
        options: { selector: ':root, [data-theme]', outputReferences: true },
      },
    );
  }

  const sd = new StyleDictionary({
    source: ['tokens/base/**/*.json', 'tokens/components/**/*.json', `tokens/themes/${id}/tokens.json`],
    usesDtcg: true,
    log: { verbosity: 'silent', warnings: 'disabled' },
    platforms: {
      css: { prefix: 'argiva', transforms: ['name/kebab'], buildPath: `${CSS}/`, files },
    },
  });
  await sd.buildAllPlatforms();
}

const read = (f) => readFileSync(path.join(CSS, f), 'utf8');
writeFileSync(
  path.join(CSS, 'argiva.css'),
  ['base.css', 'components.css', ...manifests.map((m) => `themes/${m.id}.css`)].map(read).join('\n'),
);

writeFileSync(
  path.join(DIST, 'index.js'),
  `// Generated by scripts/build.mjs. Do not edit.
export const themes = Object.freeze(${JSON.stringify(manifests, null, 2)});
export const themeIds = Object.freeze(themes.map((t) => t.id));
export const defaultThemeId = ${JSON.stringify(defaultTheme.id)};
export function isThemeId(value) {
  return typeof value === 'string' && themeIds.includes(value);
}
export function getTheme(id) {
  return themes.find((t) => t.id === id) ?? themes.find((t) => t.id === defaultThemeId);
}
`,
);

writeFileSync(
  path.join(DIST, 'index.d.ts'),
  `// Generated by scripts/build.mjs. Do not edit.
export type ThemeId = ${manifests.map((m) => JSON.stringify(m.id)).join(' | ')};
export interface ThemeFont {
  family: string;
  weights: number[];
  axes?: Record<string, [number, number]>;
  source: 'google' | 'self';
}
export interface ThemeManifest {
  id: ThemeId;
  label: string;
  description: string;
  default: boolean;
  fonts: ThemeFont[];
  ornaments: {
    purityBadge: 'hallmark' | 'text';
    divider: 'rule' | 'ghungroo';
    /** "all", "page:<slug>" or "collection:<slug>". */
    dividerScope: string[];
    heroMedia: 'rect' | 'arch';
  };
}
export declare const themes: readonly ThemeManifest[];
export declare const themeIds: readonly ThemeId[];
export declare const defaultThemeId: ThemeId;
export declare function isThemeId(value: unknown): value is ThemeId;
export declare function getTheme(id: string): ThemeManifest;
`,
);

writeFileSync(path.join(DIST, 'preview.html'), previewPage());
console.log(`Built ${manifests.length} themes into dist/ (default: ${defaultTheme.id}). Open dist/preview.html to review.`);

